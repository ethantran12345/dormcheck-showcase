-- school_directory: authoritative email-domain -> university name reference table,
-- seeded from College Emails.xlsx (1,581 rows incl. hand-added cmu.edu), and
-- get_waitlist_rank updated to resolve leaderboard names from it (crowd-sourced
-- mode() of typed names remains the fallback). Name resolution only: signup
-- counting and the INSERT-only RLS on university_waitlist are untouched.

CREATE TABLE public.school_directory (
  email_domain    text PRIMARY KEY,
  university_name text NOT NULL,
  created_at      timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.school_directory IS
  'Authoritative email-domain -> university name lookup. Reference data seeded from '
  'College Emails.xlsx; read by get_waitlist_rank for leaderboard names and used as the '
  'expansion target list. Not user data.';

-- Locked down: no client access. get_waitlist_rank is SECURITY DEFINER, so it reads
-- this without an anon/authenticated SELECT grant. If a client ever needs to read it
-- directly, add a read-only SELECT policy then; not now.
ALTER TABLE public.school_directory ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.school_directory FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.school_directory TO service_role;


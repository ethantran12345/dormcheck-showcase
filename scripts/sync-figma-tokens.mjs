#!/usr/bin/env node
/**
 * sync-figma-tokens.mjs - push src/design/tokens.json into the Figma "DormCheck Tokens"
 * variable collection (VariableCollectionId:2:3) so design + code stay on one source of truth.
 *
 * CODE IS CANONICAL: tokens.json (authored to match tailwind.config.ts + src/index.css) is the
 * source; this script projects it into Figma. Direction is one-way (code -> Figma).
 *
 * HOW IT RUNS:
 *   The Figma Plugin API is only reachable through the Figma MCP `use_figma` tool (it runs JS
 *   inside the file), not from a standalone Node process. So this script does NOT call Figma
 *   directly - it deterministically GENERATES the Plugin-API program from tokens.json and prints
 *   it to stdout. An agent (or CI step) with the Figma MCP then executes that program via
 *   `use_figma`. This keeps the transform in version control and reproducible.
 *
 *   Usage:
 *     node scripts/sync-figma-tokens.mjs            # print the Figma program to stdout
 *     node scripts/sync-figma-tokens.mjs --specs    # print the resolved token specs as JSON
 *     node scripts/sync-figma-tokens.mjs --out FILE  # also write the program to FILE
 *
 *   The generated program is idempotent: it upserts each managed variable (creating it with the
 *   right scopes if missing), skips values that already match, and treats `color/background` as a
 *   GUARDED token - it reports the off-white(code) vs white(Figma) mismatch instead of silently
 *   overwriting, because that is a deliberate design<->code reconciliation, not a typo.
 *
 * DESIGNER-DRIVEN ALTERNATIVE: the Tokens Studio for Figma plugin can also read tokens.json
 * (point its sync at this file) for a UI-driven round trip. This script remains the canonical,
 * scriptable path; see docs/design-tokens.md.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(
  readFileSync(resolve(__dirname, "../src/design/tokens.json"), "utf8"),
);

const COLLECTION_ID = tokens.$meta.figmaCollectionId; // "VariableCollectionId:2:3"
const COLLECTION_NAME = tokens.$meta.figmaCollection; // "DormCheck Tokens"
const COLOR_SCOPES = ["FRAME_FILL", "SHAPE_FILL", "TEXT_FILL", "STROKE_COLOR"];
const RADIUS_SCOPES = ["CORNER_RADIUS"];
const SPACING_SCOPES = ["WIDTH_HEIGHT", "GAP"];

/** "#RRGGBB" -> {r,g,b,a} in 0..1 (Figma color space). */
function hexToRgba(hex) {
  const h = hex.replace("#", "");
  return {
    r: parseInt(h.slice(0, 2), 16) / 255,
    g: parseInt(h.slice(2, 4), 16) / 255,
    b: parseInt(h.slice(4, 6), 16) / 255,
    a: 1,
  };
}

// Build the managed spec list. `surface` (the white card surface) maps to Figma's `color/card`,
// which was previously an alias to `color/background`; we de-aliased it so card stays white while
// the page background is the cool off-white. Every other color maps to `color/<key>`.
const FIGMA_COLOR_NAME = { surface: "color/card" };
const specs = [];
for (const [key, t] of Object.entries(tokens.color)) {
  specs.push({
    name: FIGMA_COLOR_NAME[key] || `color/${key}`,
    type: "COLOR",
    value: hexToRgba(t.hex),
    display: t.hex,
    scopes: COLOR_SCOPES,
    // No guarded tokens currently. `color/background` was reconciled to the code off-white (#F2F4F7);
    // set `guard: true` on any token whose Figma value should be reported rather than overwritten.
    guard: false,
  });
}
for (const [key, val] of Object.entries(tokens.radius)) {
  if (key.startsWith("$")) continue;
  specs.push({ name: `radius/${key}`, type: "FLOAT", value: val, display: `${val}px`, scopes: RADIUS_SCOPES });
}
for (const [key, val] of Object.entries(tokens.spacing)) {
  if (key.startsWith("$")) continue;
  specs.push({ name: `spacing/${key}`, type: "FLOAT", value: val, display: `${val}px`, scopes: SPACING_SCOPES });
}

if (process.argv.includes("--specs")) {
  process.stdout.write(JSON.stringify({ collection: COLLECTION_NAME, id: COLLECTION_ID, specs }, null, 2) + "\n");
  process.exit(0);
}

// Generate the Figma Plugin-API program (executed via the Figma MCP `use_figma` tool).
const program = `// AUTO-GENERATED by scripts/sync-figma-tokens.mjs - do not edit by hand.
// Upserts the "DormCheck Tokens" collection from src/design/tokens.json. Idempotent + guarded.
const COLLECTION_ID = ${JSON.stringify(COLLECTION_ID)};
const COLLECTION_NAME = ${JSON.stringify(COLLECTION_NAME)};
const SPECS = ${JSON.stringify(specs)};

const EPS = 0.003; // ~0.5/255 - tolerate float round-trip on color channels
const colorsEqual = (a, b) =>
  a && b && typeof a === "object" && a.type !== "VARIABLE_ALIAS" &&
  Math.abs(a.r - b.r) < EPS && Math.abs(a.g - b.g) < EPS &&
  Math.abs(a.b - b.b) < EPS && Math.abs((a.a ?? 1) - (b.a ?? 1)) < EPS;

let collection = await figma.variables.getVariableCollectionByIdAsync(COLLECTION_ID);
if (!collection) {
  const all = await figma.variables.getLocalVariableCollectionsAsync();
  collection = all.find((c) => c.name === COLLECTION_NAME) || figma.variables.createVariableCollection(COLLECTION_NAME);
}
const modeId = collection.defaultModeId;

const existing = {};
for (const id of collection.variableIds) {
  const v = await figma.variables.getVariableByIdAsync(id);
  if (v) existing[v.name] = v;
}

const diff = [];
const createdNodeIds = [];
const mutatedNodeIds = [];
for (const spec of SPECS) {
  let v = existing[spec.name];
  const isColor = spec.type === "COLOR";
  if (!v) {
    v = figma.variables.createVariable(spec.name, collection, isColor ? "COLOR" : "FLOAT");
    v.scopes = spec.scopes;
    v.setValueForMode(modeId, spec.value);
    createdNodeIds.push(v.id);
    diff.push({ name: spec.name, action: "created", to: spec.display });
    continue;
  }
  const cur = v.valuesByMode[modeId];
  if (cur && cur.type === "VARIABLE_ALIAS") { diff.push({ name: spec.name, action: "skip-alias" }); continue; }
  const same = isColor ? colorsEqual(cur, spec.value) : cur === spec.value;
  if (same) { diff.push({ name: spec.name, action: "unchanged" }); continue; }
  if (spec.guard) { diff.push({ name: spec.name, action: "FLAGGED-needs-reconcile", from: cur, to: spec.value, note: "code off-white vs Figma - not overwritten" }); continue; }
  v.setValueForMode(modeId, spec.value);
  mutatedNodeIds.push(v.id);
  diff.push({ name: spec.name, action: "updated", from: cur, to: spec.value });
}

return {
  collection: collection.name,
  modeId,
  counts: diff.reduce((acc, d) => ((acc[d.action] = (acc[d.action] || 0) + 1), acc), {}),
  diff,
  createdNodeIds,
  mutatedNodeIds,
};
`;

const outFlag = process.argv.indexOf("--out");
if (outFlag !== -1 && process.argv[outFlag + 1]) {
  writeFileSync(resolve(process.cwd(), process.argv[outFlag + 1]), program);
  process.stderr.write(`Wrote Figma sync program to ${process.argv[outFlag + 1]}\n`);
}
process.stdout.write(program);

#!/usr/bin/env bash
#
# One-command Android live reload - the Android mirror of scripts/ios-live-local.sh.
#
# Edit files in src/ and watch the emulator (or a USB device) hot-reload from the
# running Vite dev server, with no rebuild. This syncs the dev-server URL into the
# generated native config, builds+installs the debug APK, and launches it.
#
# The Android-specific gotcha: on the emulator, `localhost` resolves to the
# emulator itself, NOT your Mac. Two ways to reach the host dev server:
#   - `adb reverse tcp:8080 tcp:8080` -> then http://localhost:8080 works. This
#     also works on USB-attached physical devices, so it's what we use (and it
#     keeps CAP_SERVER_URL identical to iOS).
#   - http://10.0.2.2:8080 - the emulator-only host-loopback alias (no adb needed,
#     but emulator-only). Use it via CAP_SERVER_URL if you prefer.
# See docs/audits/capacitor-native.md.
#
# Self-contained: if the Vite dev server isn't already running, this starts it in
# the background, then keeps it in the foreground so you can watch HMR logs and
# Ctrl+C to stop everything. If a dev server is already up (e.g. you ran
# `npm run dev` in another terminal), it's reused and left running.
#
# Usage:   npm run android:live:local
#          CAP_SERVER_URL=http://10.0.2.2:8080 npm run android:live:local     # emulator host-loopback alias
#          VITE_LAN=1 CAP_SERVER_URL=http://<lan-ip>:8080 npm run android:live:local   # physical device over LAN
#          (Vite binds loopback only unless VITE_LAN=1; a reused server must have been started with it)
#
# ⚠  The generated android/app/src/main/assets/capacitor.config.json is gitignored
#    (regenerated by every sync), so the dev URL can't be committed from there. Run
#    `npm run android:reset` to regenerate it clean, and the commit guard
#    (`npm run check:android-live-reload`) is a belt-and-braces backstop.
#
set -euo pipefail

# Auto-detect a JDK (Android Studio JBR / macOS java_home) so Gradle builds work
# from the terminal even when JAVA_HOME is unset. Respects an already-set JAVA_HOME.
source "$(dirname "$0")/lib/ensure-java-home.sh" || exit 1

CAP_SERVER_URL="${CAP_SERVER_URL:-http://localhost:8080}"
VITE_LOG="${VITE_LOG:-/tmp/dormcheck-vite.log}"
APP_ID="com.dormcheck.android"

# Locate the Android SDK tools (adb/emulator are usually not on PATH).
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-$HOME/Library/Android/sdk}}"
ADB="${SDK}/platform-tools/adb"
EMULATOR="${SDK}/emulator/emulator"
[ -x "${ADB}" ] || { echo "✗ adb not found at ${ADB} (set ANDROID_HOME)."; exit 1; }
[ -x "${EMULATOR}" ] || { echo "✗ emulator not found at ${EMULATOR} (set ANDROID_HOME)."; exit 1; }

STARTED_VITE=0
VITE_PID=""
cleanup() {
  if [ "${STARTED_VITE}" = "1" ] && [ -n "${VITE_PID}" ]; then
    echo ""
    echo "→ Stopping dev server (pid ${VITE_PID})…"
    kill "${VITE_PID}" 2>/dev/null || true
  fi
}
trap cleanup EXIT INT TERM

# 1) Ensure the Vite dev server is running (start it if not).
if curl -sf -o /dev/null "${CAP_SERVER_URL}/"; then
  echo "→ Reusing dev server already running at ${CAP_SERVER_URL}"
else
  echo "→ Starting Vite dev server (logs: ${VITE_LOG})…"
  npm run dev > "${VITE_LOG}" 2>&1 &
  VITE_PID=$!
  STARTED_VITE=1
  for _ in $(seq 1 60); do
    curl -sf -o /dev/null "${CAP_SERVER_URL}/" && break
    sleep 1
  done
  if ! curl -sf -o /dev/null "${CAP_SERVER_URL}/"; then
    echo "✗ Dev server failed to start within 60s; see ${VITE_LOG}"
    exit 1
  fi
  echo "  dev server up (pid ${VITE_PID})"
fi

# 2) Ensure an emulator/device is available (boot the AVD if none).
#
#    Booting is a two-stage check, because a CORRUPT `default_boot` snapshot restores
#    in ~1s and reports sys.boot_completed=1 while the UI is a black screen and adb is
#    wedged. So we also verify the window manager is actually serving a focused window,
#    and if it isn't, we kill the emulator and cold-boot past the bad snapshot.
EMU_LOG=/tmp/dormcheck-emulator.log
UI_READY_TIMEOUT="${UI_READY_TIMEOUT:-60}"

# Is the UI actually up? (activity service alive AND a window has focus)
ui_is_live() {
  "${ADB}" shell service check activity 2>/dev/null | grep -q 'found' || return 1
  "${ADB}" shell dumpsys window 2>/dev/null | grep -q 'mCurrentFocus'
}

# Hard-stop any running emulator and reset the adb server (a wedged emulator leaves
# adb reporting the device "offline" forever until the server is restarted).
#    We must WAIT for the qemu process to actually exit: relaunching while the old one
#    is still shutting down fails hard with "Running multiple emulators with the same
#    AVD is an experimental feature".
kill_emulator() {
  "${ADB}" emu kill >/dev/null 2>&1 || true
  for _ in $(seq 1 30); do
    pgrep -f 'qemu-system' >/dev/null 2>&1 || break
    sleep 1
  done
  if pgrep -f 'qemu-system' >/dev/null 2>&1; then
    pkill -9 -f 'qemu-system' >/dev/null 2>&1 || true
    for _ in $(seq 1 20); do
      pgrep -f 'qemu-system' >/dev/null 2>&1 || break
      sleep 1
    done
  fi
  "${ADB}" kill-server >/dev/null 2>&1 || true
  "${ADB}" start-server >/dev/null 2>&1 || true
}

# `adb wait-for-device` blocks forever if the emulator never comes up (e.g. it died at
# startup), so poll with a bound instead.
wait_for_device() {
  for _ in $(seq 1 180); do
    [ -n "$("${ADB}" devices | awk '$2 == "device" { print $1; exit }')" ] && return 0
    pgrep -f 'qemu-system' >/dev/null 2>&1 || { echo "  emulator process exited - see ${EMU_LOG}"; return 1; }
    sleep 1
  done
  return 1
}

# Boot the AVD, wait for it, and report whether the UI came up. Extra args are
# passed through to the emulator (we use -no-snapshot-load on the retry).
boot_avd() {
  "${EMULATOR}" -avd "${AVD}" -netdelay none -netspeed full "$@" >"${EMU_LOG}" 2>&1 &
  echo "  waiting for device…"
  wait_for_device || return 1
  # Stage 1: Android reports boot complete.
  for _ in $(seq 1 120); do
    [ "$("${ADB}" shell getprop sys.boot_completed 2>/dev/null | tr -d '\r')" = "1" ] && break
    sleep 1
  done
  # Stage 2: the UI is genuinely alive (catches the black-screen bad-snapshot case).
  "${ADB}" shell input keyevent KEYCODE_WAKEUP >/dev/null 2>&1 || true
  for _ in $(seq 1 "${UI_READY_TIMEOUT}"); do
    ui_is_live && return 0
    sleep 1
  done
  return 1
}

DEVICE_ID="$("${ADB}" devices | awk '$2 == "device" { print $1; exit }')"
# An already-"booted" device can still be wedged (that is exactly how the bad-snapshot
# failure presents), so hold it to the same liveness bar as a fresh boot.
if [ -n "${DEVICE_ID}" ]; then
  "${ADB}" -s "${DEVICE_ID}" shell input keyevent KEYCODE_WAKEUP >/dev/null 2>&1 || true
  if ui_is_live; then
    echo "→ Reusing device already booted: ${DEVICE_ID}"
  else
    echo "⚠ Device ${DEVICE_ID} is attached but its UI is not responding - discarding it."
    kill_emulator
    DEVICE_ID=""
  fi
fi
if [ -z "${DEVICE_ID}" ]; then
  AVD="${ANDROID_AVD:-$("${EMULATOR}" -list-avds 2>/dev/null | grep -x 'dormcheck-pixel8' || "${EMULATOR}" -list-avds 2>/dev/null | head -1)}"
  [ -n "${AVD}" ] || { echo "✗ No running device and no AVD to boot (create one in Android Studio)."; exit 1; }
  echo "ℹ No device booted - starting AVD '${AVD}'…"
  if ! boot_avd; then
    echo "⚠ Emulator booted but the UI never came up within ${UI_READY_TIMEOUT}s."
    echo "  Snapshot appears bad (black screen / wedged adb) - cold-booting without it…"
    kill_emulator
    # -no-snapshot-save too: otherwise the emulator re-writes the bad snapshot on exit
    # and the next run inherits the same black screen.
    if ! boot_avd -no-snapshot-load -no-snapshot-save; then
      echo "✗ Emulator failed to reach a live UI even on a cold boot; see ${EMU_LOG}"
      echo "ℹ The emulator runs in the background from this script, but if you retry it"
      echo "  MANUALLY, start it with '&' or nohup and run adb from a DIFFERENT terminal -"
      echo "  a foreground emulator swallows your keystrokes as its own stdin."
      exit 1
    fi
    echo "  cold boot succeeded."
  fi
  DEVICE_ID="$("${ADB}" devices | awk '$2 == "device" { print $1; exit }')"
  [ -n "${DEVICE_ID}" ] || { echo "✗ Emulator failed to finish booting; see ${EMU_LOG}"; exit 1; }
fi
echo "→ Device: ${DEVICE_ID}"

# 3) For the localhost case, reverse-tunnel the dev-server port to the host.
#    (Skip for 10.0.2.2 / LAN IPs, which already reach the host directly.)
HOST="$(printf '%s' "${CAP_SERVER_URL}" | sed -E 's#^https?://([^:/]+).*#\1#')"
PORT="$(printf '%s' "${CAP_SERVER_URL}" | sed -E 's#^https?://[^:/]+:?([0-9]*).*#\1#')"
PORT="${PORT:-8080}"
if [ "${HOST}" = "localhost" ] || [ "${HOST}" = "127.0.0.1" ]; then
  echo "→ adb reverse tcp:${PORT} tcp:${PORT} (host dev server reachable as localhost)"
  "${ADB}" -s "${DEVICE_ID}" reverse "tcp:${PORT}" "tcp:${PORT}"
fi

# 3.5) Purge iCloud " 2" duplicate files under android/ (recurring gotcha that
#      breaks the Gradle build when the checkout lives in iCloud-synced Documents).
find android -name '* 2.*' -type f -print -delete 2>/dev/null || true

# 4) Sync the env-gated server block into the generated native config, then
#    build + install + launch the debug build on the device.
echo "→ Syncing native config (CAP_SERVER_URL=${CAP_SERVER_URL})"
CAP_SERVER_URL="${CAP_SERVER_URL}" npx cap sync android

#    We deliberately do NOT use `npx cap run android`: it delegates to native-run,
#    which launches with `am start -W` (block until the activity finishes launching)
#    behind a hardcoded 5000ms adb timeout. A live-reload cold start exceeds that, so
#    native-run kills the adb server and reports "Deploying app-debug.apk failed" -
#    AFTER the install already succeeded. Gradle + a plain `am start` avoids that.
echo "→ Building + installing on ${DEVICE_ID}…"
( cd android && ANDROID_SERIAL="${DEVICE_ID}" ./gradlew installDebug )

# NOTE: com.dormcheck.android/com.dormcheck.ios.MainActivity LOOKS like a typo and is
# correct - build.gradle `namespace` is com.dormcheck.ios (legacy iOS-first Java
# package) while `applicationId` is com.dormcheck.android (the Play package). Android
# allows these to differ. Do not "fix" it; renaming is a store-identity change.
echo "→ Launching…"
# `am start` exits 0 even when it prints "Error: Activity class ... does not exist",
# so inspect the output rather than trusting the exit code.
LAUNCH_OUT="$("${ADB}" -s "${DEVICE_ID}" shell am start -n com.dormcheck.android/com.dormcheck.ios.MainActivity 2>&1)" || true
echo "${LAUNCH_OUT}"
if printf '%s' "${LAUNCH_OUT}" | grep -qiE '^Error|does not exist|device offline'; then
  echo "✗ Launch failed. The device is most likely wedged - re-run this script; it will"
  echo "  detect the dead UI and cold-boot the emulator."
  echo "ℹ Run adb from a DIFFERENT terminal than the emulator, or start the emulator with"
  echo "  nohup/& - a foreground emulator swallows your keystrokes as its own stdin."
  exit 1
fi

echo ""
echo "✅ Live reload active - edit files in src/ and watch the device update."
echo "⚠  Before any commit, run:  npm run android:reset   (strips the dev server.url)"

# 5) If we started the dev server, keep it in the foreground (Ctrl+C stops it).
if [ "${STARTED_VITE}" = "1" ]; then
  echo "→ Streaming dev-server logs. Press Ctrl+C to stop the dev server and exit."
  tail -f "${VITE_LOG}"
else
  echo "ℹ Dev server was already running (started outside this script) - leaving it up."
fi

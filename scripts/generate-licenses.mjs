#!/usr/bin/env node
/**
 * Generate the open-source acknowledgements manifest shown at `/licenses`.
 *
 * Reads the app's DIRECT production dependencies from `package.json`
 * (`dependencies`), then resolves each installed package's real
 * `name` / `version` / `license` / `homepage` from its `node_modules`
 * `package.json`. Output is written to `src/data/licenses.generated.json`
 * and committed, so the page renders from real, reproducible data with no
 * build-time filesystem access.
 *
 * Re-run after changing dependencies:  `node scripts/generate-licenses.mjs`
 *
 * Scope note: this lists the direct production dependencies DormCheck declares
 * (not the full transitive tree, and not devDependencies which never ship to
 * users). That is the standard "acknowledgements" surface and keeps the list
 * honest and legible.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const deps = Object.keys(pkg.dependencies || {}).sort((a, b) =>
  a.toLowerCase().localeCompare(b.toLowerCase()),
);

/** Turn a git/repo URL into a plain browsable https URL. */
function normalizeUrl(url, name) {
  if (!url) return `https://www.npmjs.com/package/${name}`;
  let u = url.trim().replace(/^git\+/, '').replace(/\.git$/, '');
  if (u.startsWith('git://')) u = 'https://' + u.slice('git://'.length);
  if (u.startsWith('git@github.com:')) u = 'https://github.com/' + u.slice('git@github.com:'.length);
  if (u.startsWith('ssh://git@')) u = 'https://' + u.slice('ssh://git@'.length);
  if (!/^https?:\/\//.test(u)) return `https://www.npmjs.com/package/${name}`;
  return u;
}

/** Normalize the many shapes a package's license field can take into a string. */
function readLicense(meta) {
  if (typeof meta.license === 'string') return meta.license;
  if (meta.license && typeof meta.license === 'object' && meta.license.type) {
    return meta.license.type;
  }
  if (Array.isArray(meta.licenses)) {
    return meta.licenses.map((l) => (typeof l === 'string' ? l : l.type)).filter(Boolean).join(', ');
  }
  if (meta.licenses && meta.licenses.type) return meta.licenses.type;
  return 'See package';
}

const packages = [];
const missing = [];

for (const name of deps) {
  try {
    const metaPath = join(root, 'node_modules', name, 'package.json');
    const meta = JSON.parse(readFileSync(metaPath, 'utf8'));
    packages.push({
      name,
      version: meta.version || pkg.dependencies[name],
      license: readLicense(meta),
      homepage: normalizeUrl(
        meta.homepage ||
          (meta.repository &&
            (typeof meta.repository === 'string'
              ? meta.repository
              : meta.repository.url)),
        name,
      ),
    });
  } catch {
    missing.push(name);
  }
}

if (missing.length) {
  // Don't fabricate entries for packages we couldn't resolve - surface them.
  console.warn(`[licenses] could not resolve ${missing.length}: ${missing.join(', ')}`);
}

const out = {
  note: 'Generated by scripts/generate-licenses.mjs from installed production dependencies. Do not edit by hand.',
  count: packages.length,
  packages,
};

const dest = join(root, 'src', 'data', 'licenses.generated.json');
writeFileSync(dest, JSON.stringify(out, null, 2) + '\n');
console.log(`[licenses] wrote ${packages.length} packages to ${dest}`);

#!/usr/bin/env node
/**
 * AGENTS.md generator.
 *
 * AGENTS.md is the cross-tool convention (Codex reads it; so do several editors).
 * It was previously a hand-maintained COPY of CLAUDE.md produced by a `Claude`→`Codex`
 * find-replace that over-matched: it told agents to run `npm run check:Codex-md`, cited
 * `scripts/check-Codex-md-budget.mjs`, and pointed at `.Codex/rules/`. None of those
 * exist. It had also already drifted from its source (14,710 vs 14,735 bytes).
 *
 * Two hand-maintained copies of the same content is the exact drift failure the docs
 * guard exists to stop, so AGENTS.md is now GENERATED and `docs:check` fails on a diff.
 *
 * DESIGN: the body is CLAUDE.md **verbatim**, with zero substitutions. The tempting
 * "narrow substitution list" is still a footgun — `Claude` appears in real command
 * names (`check:claude-md`), real paths (`.claude/rules/`), and real proper nouns
 * ("Claude in Xcode", "Claude Code" as the name of a *role* in the agent-roles split).
 * Rewriting any of those produces exactly the fabricated paths this replaces. Instead a
 * generated preamble tells the reading agent which role it plays and that the
 * `.claude/`-prefixed paths below are literal.
 *
 * Usage:
 *   node scripts/gen-agents-md.mjs            write AGENTS.md
 *   node scripts/gen-agents-md.mjs --check    exit 1 if AGENTS.md is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const PREAMBLE = `---
description:
alwaysApply: true
---

<!-- GENERATED FROM CLAUDE.md by scripts/gen-agents-md.mjs — DO NOT EDIT THIS FILE.
     Edit CLAUDE.md, then run \`npm run gen:agents\`. \`npm run docs:check\` fails on drift. -->

# AGENTS.md

Guidance for any coding agent working in this repository (Codex, Cursor, and anything else
that reads \`AGENTS.md\`). The body below is **CLAUDE.md verbatim** — one source, no copy.

Two things to read it correctly:

1. **You play the "Claude Code" role** described under "Agent roles": everything in \`src/\`,
   Supabase, Vercel \`/api\`, git, npm scripts, tests, \`npm run build:ios\`. You are *not* the
   native \`ios/\` agent and not Cowork. The same one-agent-per-area rule binds you.
2. **Every \`.claude/\`-prefixed path and every \`claude\`-containing command below is
   literal.** \`.claude/rules/\`, \`.claude/commands/\`, \`npm run check:claude-md\`, and
   \`scripts/check-claude-md-budget.mjs\` are the real names on disk regardless of which
   agent you are. There is no \`.codex/rules/\` and no \`check:codex-md\`. Do not translate
   them; do not invent parallel copies.

---

`;

export function renderAgentsMd() {
  const claude = readFileSync(join(REPO_ROOT, "CLAUDE.md"), "utf8");
  // Drop CLAUDE.md's own frontmatter + H1 + one-line subtitle; the preamble replaces them.
  const body = claude.replace(/^---\n[\s\S]*?\n---\n+# CLAUDE\.md\n+.*\n+/, "");
  return PREAMBLE + body;
}

const AGENTS_PATH = join(REPO_ROOT, "AGENTS.md");

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const expected = renderAgentsMd();
  if (process.argv.includes("--check")) {
    const actual = readFileSync(AGENTS_PATH, "utf8");
    if (actual !== expected) {
      console.error("AGENTS.md is out of date with CLAUDE.md. Run `npm run gen:agents`.");
      process.exit(1);
    }
    console.log("AGENTS.md is in sync with CLAUDE.md.");
  } else {
    writeFileSync(AGENTS_PATH, expected);
    console.log(`Wrote AGENTS.md (${Buffer.byteLength(expected)} bytes) from CLAUDE.md.`);
  }
}
